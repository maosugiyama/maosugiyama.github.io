const map=new Map();
L.forEach(e=>{
  const k=norm(e.w);
  if(DROP.has(k)) return;
  let m=e.m.replace(/[／\s↔（×]+$/,'').trim();
  let p=e.p;
  if(OV[k]){ m=OV[k][0]; if(OV[k][1]) p=OV[k][1]; }
  m=m.replace(/\s*(単数|複数)$/,'');
  if(!map.has(k)) map.set(k,{w:e.w,m,p,us:e.us});
});
EXTRA.forEach(([w,m,p,u])=>{
  const k=norm(w);
  if(map.has(k)){ const x=map.get(k); if(!x.us.includes(u)) x.us.push(u); }
  else map.set(k,{w,m,p,us:[u]});
});
const out=[...map.values()];
out.sort((a,b)=>norm(a.w).localeCompare(norm(b.w),'ru'));
const cnt={};
out.forEach(e=>cnt[e.p]=(cnt[e.p]||0)+1);
console.log('見出し '+out.length+' 語 '+JSON.stringify(cnt));
